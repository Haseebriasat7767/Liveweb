/**
 * FLOOR PLAN EXPERIENCE
 * Each level is drawn as an SVG on a 1200 × 720 stage. Rooms are interactive:
 * hovering or selecting highlights the room and reveals its data.
 * Areas are indicative and reconcile with the published statistics.
 */

export type PlanRoom = {
  id: string;
  name: string;
  /** Short label drawn inside the room on the plan. */
  short: string;
  area: string;
  dimensions: string;
  /** SVG geometry — rectangle or polygon points on the 1200 × 720 stage. */
  x?: number;
  y?: number;
  w?: number;
  h?: number;
  points?: string;
  /** Type groups the room for styling (interior / service / exterior / circulation). */
  kind: 'principal' | 'private' | 'service' | 'exterior' | 'circulation';
  /** Optional linked photography. */
  imageSrc?: string;
  imageAlt?: string;
  /** Optional extended description. */
  detail?: string;
  /** Hidden from the selectable room list (e.g. plant rooms). */
  minor?: boolean;
};

export type PlanLevel = {
  id: string;
  name: string;
  short: string;
  /** Elevation label, shown as a small marker (e.g. +14′-0″). */
  elevation: string;
  /** Indicative summary shown above the plan. */
  summary: string;
  totalArea: string;
  rooms: PlanRoom[];
  /** Decorative masonry / capsule walls drawn beneath the rooms. */
  shell?: string[];
};

